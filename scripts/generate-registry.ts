#!/usr/bin/env tsx
/**
 * generate-registry.ts
 * Genera src/registry/registry.generated.ts con if/else if literales
 * de process.env.EXPO_PUBLIC_GAME_ID para tree-shaking de Metro.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = path.join(ROOT, "src", "registry", "registry.generated.ts");

const GAME_IDS = [
  "arkanoid", "asteroids", "centipede", "echorunner", "flappybird", "frogger",
  "galaxian", "geometrywars", "hitandrun", "outrun", "platformer", "pong",
  "racing", "space-invaders", "tower-defense", "vertical-shmup",
  "campaign", "cyoa", "blindstation",
] as const;

type GameId = (typeof GAME_IDS)[number];

function entryPathFor(id: GameId): string {
  return `../app/${id}/index`;
}

function generate(): string {
  const lines: string[] = [];
  lines.push(`/**`);
  lines.push(` * AUTO-GENERATED by scripts/generate-registry.ts`);
  lines.push(` * No editar a mano.`);
  lines.push(` */`);
  lines.push(``);
  lines.push(`import type { ComponentType } from "react";`);
  lines.push(``);
  lines.push(`export type GameScreen = ComponentType<Record<string, unknown>>;`);
  lines.push(``);
  lines.push(`export function resolveGameScreen(): GameScreen | null {`);
  lines.push(`  // No extraer process.env.EXPO_PUBLIC_GAME_ID a constante intermedia.`);
  lines.push(``);
  for (let i = 0; i < GAME_IDS.length; i++) {
    const id = GAME_IDS[i];
    const keyword = i === 0 ? "if" : "else if";
    lines.push(`  ${keyword} (process.env.EXPO_PUBLIC_GAME_ID === "${id}") {`);
    lines.push(`    // eslint-disable-next-line @typescript-eslint/no-require-imports`);
    lines.push(`    return require("${entryPathFor(id)}").default as GameScreen;`);
    lines.push(`  }`);
  }
  lines.push(`  return null;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export function isSingleGameBuild(): boolean {`);
  lines.push(`  return typeof process.env.EXPO_PUBLIC_GAME_ID === "string"`);
  lines.push(`    && process.env.EXPO_PUBLIC_GAME_ID.length > 0;`);
  lines.push(`}`);
  lines.push(``);
  return lines.join("\n");
}

function main() {
  const outDir = path.dirname(OUT_FILE);
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(OUT_FILE, generate(), "utf8");
  console.log(`✅ Wrote ${path.relative(ROOT, OUT_FILE)} (${GAME_IDS.length} branches)`);
}

main();
